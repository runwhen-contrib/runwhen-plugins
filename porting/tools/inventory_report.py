"""Render porting/inventory.md from porting/inventory/*.yaml and porting/parity.yaml (CNT-1)."""

from __future__ import annotations

import sys
from collections import Counter, defaultdict
from pathlib import Path

import yaml

SOURCE_SHA = "49ab483"
PLUGINS = ("kubernetes", "azure", "aws", "gcp", "misc")
PREFIX_PLUGIN = {"k8s-": "kubernetes", "azure-": "azure", "aws-": "aws", "gcp-": "gcp"}

# Bundles in the July checkout (432f1d6) the parity call was made on. Its "94" counted
# `ls codebundles | wc -l`, which includes CURSOR_RULES_README.md: the real figure is 93
# (k8s 46, azure 24, aws 6, gcp 4, misc 13). Since then 27 gcp-* bundles and gh-repo-health arrived.
BASELINE_COUNTS = {"kubernetes": 46, "azure": 24, "aws": 6, "gcp": 4, "misc": 13}
ADDED_SINCE_BASELINE = frozenset({"gh-repo-health"})
BASELINE_GCP = frozenset(
    {
        "gcp-bucket-health",
        "gcp-cloud-function-health",
        "gcp-project-cost-health",
        "gcp-vertex-modelgarden-health",
    }
)

WIDE_SCOPES = ("cluster", "all-namespaces", "secondary-ns", "subscription", "project", "account")
WRITE_OK_PREFIXES = ("chaos-", "restart-")
WRITE_OK_SUFFIXES = ("-ops", "-remediate")
WRITE_OK_BUNDLES = frozenset({"acr-image-sync"})
HOT_SPOTS = 15
WHY_LIMIT = 160


def plugin_of(bundle: str) -> str:
    for prefix, plugin in PREFIX_PLUGIN.items():
        if bundle.startswith(prefix):
            return plugin
    return "misc"


def _stem(bundle: str) -> str:
    """Bundle name without its k8s-/azure-/... prefix, for the write-allowance rules."""
    for prefix in PREFIX_PLUGIN:
        if bundle.startswith(prefix):
            return bundle[len(prefix) :]
    return bundle


def is_beyond_baseline(bundle: str) -> bool:
    if bundle in ADDED_SINCE_BASELINE:
        return True
    return bundle.startswith("gcp-") and bundle not in BASELINE_GCP


def writes_expected(bundle: str) -> bool:
    stem = _stem(bundle)
    return (
        stem in WRITE_OK_BUNDLES
        or stem.startswith(WRITE_OK_PREFIXES)
        or stem.endswith(WRITE_OK_SUFFIXES)
    )


def hidden_writes(inventory: list[dict]) -> list[tuple[str, str]]:
    return [
        (b["bundle"], t["title"])
        for b in inventory
        if not writes_expected(b["bundle"])
        for t in b["tasks"]
        if not t["readOnly"]
    ]


def _fp(tasks: list[dict]) -> Counter:
    return Counter(t["falsePass"] for t in tasks)


def _cell(text: object) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def _truncate(text: str, limit: int = WHY_LIMIT) -> str:
    text = " ".join(str(text).split())
    return text if len(text) <= limit else text[: limit - 3] + "..."


def _skills_by_bundle(parity: dict) -> dict[str, list[str]]:
    return {e["bundle"]: list(e.get("skills") or []) for e in (parity or {}).get("kubernetes", [])}


def render(inventory: list[dict], parity: dict) -> str:
    inventory = sorted(inventory, key=lambda b: b["bundle"])
    all_tasks = [t for b in inventory for t in b["tasks"]]
    fp = _fp(all_tasks)
    skills = _skills_by_bundle(parity)
    out: list[str] = []

    out += [
        "# CNT-1 inventory of rw-cli-codecollection bundles",
        "",
        f"Source: rw-cli-codecollection origin/main @ {SOURCE_SHA}. "
        "Generated by `porting/tools/inventory_report.py` from `porting/inventory/*.yaml` and "
        "`porting/parity.yaml`; do not edit by hand.",
        "",
        f"Totals: {len(inventory)} bundles, {len(all_tasks)} tasks, "
        f"{sum(1 for t in all_tasks if not t['readOnly'])} write tasks, "
        f"falsePass confirmed {fp['confirmed']} / likely {fp['likely']} / none {fp['none']}.",
        "",
    ]

    by_plugin: dict[str, list[dict]] = defaultdict(list)
    for b in inventory:
        by_plugin[plugin_of(b["bundle"])].append(b)

    # Parity baseline
    beyond = [b["bundle"] for b in inventory if is_beyond_baseline(b["bundle"])]
    base_total = sum(BASELINE_COUNTS.values())
    out += [
        "## Parity baseline",
        "",
        f"The July checkout had {base_total} bundles ("
        + ", ".join(f"{p} {BASELINE_COUNTS[p]}" for p in PLUGINS)
        + f"). main @ {SOURCE_SHA} has {len(inventory)} ("
        + ", ".join(f"{p} {len(by_plugin[p])}" for p in PLUGINS)
        + f"). {len(beyond)} bundles are beyond the baseline: `gh-repo-health` and the gcp bundles other than "
        + ", ".join(f"`{n}`" for n in sorted(BASELINE_GCP))
        + ". (The \"94\" quoted for the baseline counted a README file in `codebundles/`.)",
        "",
        f"Beyond baseline (Samir decides scope), {len(beyond)}:",
        "",
    ]
    out += [f"- `{n}` - beyond baseline (Samir decides scope)" for n in beyond]
    out.append("")

    # Per plugin
    out += ["## By plugin", ""]
    for plugin in PLUGINS:
        bundles = by_plugin[plugin]
        tasks = [t for b in bundles for t in b["tasks"]]
        f = _fp(tasks)
        out += [
            f"### {plugin} ({len(bundles)} bundles, {len(tasks)} tasks)",
            "",
            "| bundle | classic resource types | tasks | write | falsePass c/l/n | sli | V13 skills |",
            "|---|---|---|---|---|---|---|",
        ]
        for b in bundles:
            bf = _fp(b["tasks"])
            sk = skills.get(b["bundle"]) if plugin == "kubernetes" else None
            sk_cell = ", ".join(sk) if sk else "—"
            out.append(
                f"| {b['bundle']} | {_cell(', '.join(b.get('classicResourceTypes') or []) or '—')} "
                f"| {len(b['tasks'])} | {sum(1 for t in b['tasks'] if not t['readOnly'])} "
                f"| {bf['confirmed']}/{bf['likely']}/{bf['none']} | {'yes' if b.get('sli') else 'no'} "
                f"| {_cell(sk_cell)} |"
            )
        out += [
            "",
            f"Plugin totals: falsePass confirmed {f['confirmed']} / likely {f['likely']} / none {f['none']}.",
            "",
        ]

    # By classic resource type
    types: dict[str, list[str]] = defaultdict(list)
    for b in inventory:
        for rt in b.get("classicResourceTypes") or []:
            types[rt].append(b["bundle"])
    out += ["## By classic resource type", "", "| classic resource type | bundles |", "|---|---|"]
    for rt in sorted(types):
        out.append(f"| {_cell(rt)} | {', '.join(types[rt])} |")
    out.append("")

    # False-pass hot spots
    def confirmed(b: dict) -> int:
        return sum(1 for t in b["tasks"] if t["falsePass"] == "confirmed")

    ranked = sorted((b for b in inventory if confirmed(b)), key=lambda b: (-confirmed(b), b["bundle"]))
    out += [
        "## False-pass hot spots",
        "",
        f"Top {HOT_SPOTS} bundles by confirmed false-pass tasks.",
        "",
        "| bundle | confirmed | example falsePassWhy |",
        "|---|---|---|",
    ]
    for b in ranked[:HOT_SPOTS]:
        why = next(t["falsePassWhy"] for t in b["tasks"] if t["falsePass"] == "confirmed")
        out.append(f"| {b['bundle']} | {confirmed(b)} | {_cell(_truncate(why))} |")
    out.append("")

    # Wider than the target (kubernetes only)
    out += [
        "## Wider than the target",
        "",
        "Kubernetes tasks whose scope is wider than the bundle's target type "
        "(cluster-scoped tasks in a bundle that targets `cluster` are not listed).",
        "",
        "| bundle | task | scope |",
        "|---|---|---|",
    ]
    for b in by_plugin["kubernetes"]:
        cluster_target = "cluster" in (b.get("classicResourceTypes") or [])
        for t in b["tasks"]:
            if t["scope"] in WIDE_SCOPES and not (cluster_target and t["scope"] == "cluster"):
                out.append(f"| {b['bundle']} | {_cell(t['title'])} | {t['scope']} |")
    out.append("")

    # Writes hidden as reads
    out += [
        "## Writes hidden as reads",
        "",
        "Tasks with readOnly false in bundles that are not *-ops, chaos-*, restart-*, *-remediate or acr-image-sync.",
        "",
        "| bundle | task |",
        "|---|---|",
    ]
    for bundle, title in hidden_writes(inventory):
        out.append(f"| {bundle} | {_cell(title)} |")
    out.append("")

    return "\n".join(out)


def load_inventory(directory: Path) -> list[dict]:
    inventory: list[dict] = []
    for path in sorted(directory.glob("*.yaml")):
        inventory.extend(yaml.safe_load(path.read_text()))
    return inventory


def main() -> None:
    porting = Path(__file__).resolve().parent.parent
    inventory = load_inventory(porting / "inventory")
    parity = yaml.safe_load((porting / "parity.yaml").read_text())
    (porting / "inventory.md").write_text(render(inventory, parity))
    print(f"wrote {porting / 'inventory.md'}", file=sys.stderr)


if __name__ == "__main__":
    main()
